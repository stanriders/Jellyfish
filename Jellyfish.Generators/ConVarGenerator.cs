using System;
using System.Collections.Generic;
using System.Collections.Immutable;
using System.Globalization;
using System.Linq;
using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.CSharp.Syntax;
using Microsoft.CodeAnalysis.Text;

namespace Jellyfish.Generators;

[Generator]
public sealed class ConVarGenerator : IIncrementalGenerator
{
    private const string AttributeName = "Jellyfish.Console.ConVarAttribute";
    private const string ConVarStorageName = "global::Jellyfish.Console.ConVarStorage";

    private static readonly DiagnosticDescriptor NotPartial = new(
        "JFCV001",
        "ConVar property must be partial",
        "Property '{0}' has [ConVar] and must be declared partial",
        "Jellyfish",
        DiagnosticSeverity.Error,
        isEnabledByDefault: true);

    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        var properties = context.SyntaxProvider.ForAttributeWithMetadataName(
                AttributeName,
                predicate: static (node, _) => node is PropertyDeclarationSyntax,
                transform: static (ctx, _) => (IPropertySymbol)ctx.TargetSymbol)
            .Collect();

        context.RegisterSourceOutput(properties, Generate);
    }

    private static void Generate(SourceProductionContext context, ImmutableArray<IPropertySymbol> properties)
    {
        var valid = new List<(IPropertySymbol Property, string Name, string Registration)>();
        foreach (var property in properties)
        {
            if (!IsPartial(property))
            {
                var location = property.Locations.FirstOrDefault() ?? Location.None;
                context.ReportDiagnostic(Diagnostic.Create(NotPartial, location, property.Name));
                continue;
            }

            valid.Add(ParseConVar(property));
        }

        foreach (var group in valid.GroupBy(v => v.Property.ContainingType, (IEqualityComparer<INamedTypeSymbol>)SymbolEqualityComparer.Default))
        {
            var hintName = group.Key.ToDisplayString().Replace('.', '_') + ".ConVars.g.cs";
            context.AddSource(hintName, SourceText.From(ImplementationSource(group.Key, group), Encoding.UTF8));
        }

        var registration = new StringBuilder();
        registration.AppendLine("// <auto-generated/>");
        registration.AppendLine("namespace Jellyfish.Console.Generated");
        registration.AppendLine("{");
        registration.AppendLine("    internal static class ConVarRegistration");
        registration.AppendLine("    {");
        registration.AppendLine("        public static void RegisterAll()");
        registration.AppendLine("        {");
        foreach (var (_, _, convar) in valid)
            registration.AppendLine($"            {convar};");
        registration.AppendLine("        }");
        registration.AppendLine("    }");
        registration.AppendLine("}");
        context.AddSource("ConVarRegistration.g.cs", SourceText.From(registration.ToString(), Encoding.UTF8));
    }

    private static (IPropertySymbol Property, string Name, string Registration) ParseConVar(IPropertySymbol property)
    {
        var attribute = property.GetAttributes().First(a => a.AttributeClass?.ToDisplayString() == AttributeName);
        var args = attribute.ConstructorArguments;
        var name = (string)args[0].Value!;
        var type = TypeName(property.Type);

        var arguments = new List<string>
        {
            StringLiteral(name),
            args.Length > 1 ? ValueLiteral(type, args[1]) : "default",
        };

        var bind = args.Length > 2 ? BindLiteral(args[2]) : null;
        if (bind != null)
            arguments.Add(bind);

        return (property, name, $"new global::Jellyfish.Console.ConVar<{type}>({string.Join(", ", arguments)})");
    }

    private static string ImplementationSource(
        INamedTypeSymbol containingType,
        IEnumerable<(IPropertySymbol Property, string Name, string Registration)> properties)
    {
        var types = new List<INamedTypeSymbol>();
        for (var type = containingType; type != null; type = type.ContainingType)
            types.Insert(0, type);

        var source = new StringBuilder();
        var depth = 0;
        void Line(string text) => source.Append(' ', depth * 4).AppendLine(text);

        source.AppendLine("// <auto-generated/>");

        var ns = containingType.ContainingNamespace;
        if (!ns.IsGlobalNamespace)
        {
            Line($"namespace {ns.ToDisplayString()}");
            Line("{");
            depth++;
        }

        foreach (var type in types)
        {
            Line($"{Modifiers(type)} partial {TypeKeyword(type)} {type.Name}");
            Line("{");
            depth++;
        }

        foreach (var (property, name, _) in properties)
        {
            var type = TypeName(property.Type);
            Line($"{Modifiers(property)} partial {type} {property.Name}");
            Line("{");
            depth++;
            Line($"get => {ConVarStorageName}.Get<{type}>({StringLiteral(name)});");
            Line($"set => {ConVarStorageName}.Set<{type}>({StringLiteral(name)}, value);");
            depth--;
            Line("}");
        }

        while (depth > 0)
        {
            depth--;
            Line("}");
        }

        return source.ToString();
    }

    private static bool IsPartial(IPropertySymbol property) =>
        property.DeclaringSyntaxReferences
            .Select(reference => reference.GetSyntax())
            .OfType<PropertyDeclarationSyntax>()
            .Any(syntax => syntax.Modifiers.Any(modifier => modifier.RawKind == (int)SyntaxKind.PartialKeyword));

    private static string Modifiers(ISymbol symbol)
    {
        var access = symbol.DeclaredAccessibility switch
        {
            Accessibility.Public => "public",
            Accessibility.Internal => "internal",
            Accessibility.Protected => "protected",
            Accessibility.ProtectedOrInternal => "protected internal",
            Accessibility.ProtectedAndInternal => "private protected",
            _ => "private",
        };

        return symbol.IsStatic ? $"{access} static" : access;
    }

    private static string TypeKeyword(INamedTypeSymbol type)
    {
        if (type.TypeKind == TypeKind.Struct)
            return type.IsRecord ? "record struct" : "struct";

        return type.IsRecord ? "record" : "class";
    }

    private static string TypeName(ITypeSymbol type) =>
        type.SpecialType != SpecialType.None
            ? type.ToDisplayString(SymbolDisplayFormat.CSharpErrorMessageFormat)
            : type.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat);

    private static string ValueLiteral(string type, TypedConstant constant)
    {
        if (constant.IsNull)
            return "default";

        return constant.Value switch
        {
            bool value => value ? "true" : "false",
            string value => StringLiteral(value),
            _ => $"(({type}){Convert.ToString(constant.Value, CultureInfo.InvariantCulture)})",
        };
    }

    private static string? BindLiteral(TypedConstant constant)
    {
        if (constant.IsNull || constant.Type is not INamedTypeSymbol keys)
            return null;

        var value = Convert.ToInt64(constant.Value, CultureInfo.InvariantCulture);
        var member = keys.GetMembers().OfType<IFieldSymbol>()
            .FirstOrDefault(field => field.HasConstantValue && Convert.ToInt64(field.ConstantValue, CultureInfo.InvariantCulture) == value);

        if (member == null || member.Name == "Unknown")
            return null;

        return $"{TypeName(keys)}.{member.Name}";
    }

    private static string StringLiteral(string value) =>
        "\"" + value.Replace("\\", "\\\\").Replace("\"", "\\\"") + "\"";
}
